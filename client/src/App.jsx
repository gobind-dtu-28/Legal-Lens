import { useState, useRef, useEffect } from "react";
import { T, SAMPLE } from "./i18n.js";

/* ---------- helpers ---------- */
async function post(url, body) {
  const r = await fetch(url, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) });
  const d = await r.json().catch(() => ({}));
  if (!r.ok) throw new Error(d.error || "Something went wrong. Please try again.");
  return d;
}

const readAsDataURL = (f) =>
  new Promise((res, rej) => {
    const r = new FileReader();
    r.onload = () => res(r.result);
    r.onerror = () => rej(new Error("Could not read this file."));
    r.readAsDataURL(f);
  });

// Downscale big photos so requests stay small
async function loadImage(f) {
  const src = await readAsDataURL(f);
  const img = await new Promise((res, rej) => {
    const i = new Image();
    i.onload = () => res(i);
    i.onerror = () => rej(new Error("Could not read this image."));
    i.src = src;
  });
  const s = Math.min(1, 1600 / Math.max(img.width, img.height));
  const c = document.createElement("canvas");
  c.width = img.width * s;
  c.height = img.height * s;
  c.getContext("2d").drawImage(img, 0, 0, c.width, c.height);
  const url = c.toDataURL("image/jpeg", 0.85);
  return { url, image: { mime: "image/jpeg", data: url.split(",")[1] } };
}

function reportText(d, t) {
  const L = (a) => (a || []).map((x) => "- " + x);
  return [
    `${d.document_type} | Risk ${d.risk_score}/100`, d.one_line_summary, "", d.plain_summary, "",
    ...(d.key_facts || []).map((k) => `${k.label}: ${k.value}`), "",
    ...(d.risky_clauses || []).map((k) => `[${(k.severity || "").toUpperCase()}] "${k.clause_quote}"\n  ${k.plain_explanation}\n  ${t.why}: ${k.why_risky}\n  ${t.act}: ${k.suggested_action}`), "",
    t.q + ":", ...L(d.questions_to_ask), "", t.m + ":", ...L(d.missing_protections), "", t.n + ":", ...L(d.next_steps), "",
    "Generated by Legal Lens. General information only, not legal advice.",
  ].join("\n");
}

const List = ({ items }) => <ul>{(items || []).map((x, i) => <li key={i}>{x}</li>)}</ul>;

/* ---------- one risky clause, with its own "fairer wording" state ---------- */
function Clause({ k, doc, lang, t }) {
  const sev = ["high", "medium", "low"].includes(k.severity) ? k.severity : "medium";
  const [rw, setRw] = useState(null);
  async function rewrite() {
    setRw({ busy: true });
    try {
      const j = await post("/api/rewrite", { clause: k.clause_quote, issue: k.why_risky, docType: doc, lang });
      setRw({ text: j.rewritten_clause + "\n" + (j.why_fairer || "") });
    } catch (e) {
      setRw({ err: e.message });
    }
  }
  return (
    <div className={"clause " + sev}>
      <span className={"badge " + sev}>{sev}</span>
      <blockquote>“{k.clause_quote}”</blockquote>
      <div>{k.plain_explanation}</div>
      <div><b>{t.why}: </b>{k.why_risky}</div>
      <div><b>{t.act}: </b>{k.suggested_action}</div>
      <button className="ghost small" disabled={rw?.busy} onClick={rewrite}>{t.rewrite}</button>
      {rw && (
        <div className={"rewrite" + (rw.busy ? " busy" : "") + (rw.err ? " err" : "")}>
          {rw.busy ? t.rewriting : rw.err || <><b>{t.fairer}: </b>{rw.text}</>}
        </div>
      )}
    </div>
  );
}

/* ---------- results: stamp, facts, clauses, lists, chat ---------- */
function Result({ a, id, lang, t }) {
  const [speaking, setSpeaking] = useState(false);
  const [copied, setCopied] = useState(false);
  const [chat, setChat] = useState([]);
  const [q, setQ] = useState("");
  const ref = useRef(null);
  const logRef = useRef(null);

  useEffect(() => { ref.current?.scrollIntoView({ behavior: "smooth" }); }, [id]);
  useEffect(() => { if (logRef.current) logRef.current.scrollTop = 1e9; }, [chat]);
  useEffect(() => () => window.speechSynthesis?.cancel(), []);

  const s = Math.max(0, Math.min(100, +a.risk_score || 0));
  const col = s >= 67 ? "var(--high)" : s >= 34 ? "var(--med)" : "var(--low)";
  const clauses = a.risky_clauses || [];
  const cnt = { high: 0, medium: 0, low: 0 };
  clauses.forEach((k) => { if (k.severity in cnt) cnt[k.severity]++; });

  function listen() {
    const syn = window.speechSynthesis;
    if (!syn) return alert("Read aloud is not supported in this browser.");
    if (syn.speaking) { syn.cancel(); setSpeaking(false); return; }
    const u = new SpeechSynthesisUtterance([a.one_line_summary, a.plain_summary, ...clauses.map((k) => k.plain_explanation)].filter(Boolean).join(". "));
    u.lang = lang === "hi" ? "hi-IN" : "en-IN";
    u.onend = u.onerror = () => setSpeaking(false);
    syn.speak(u);
    setSpeaking(true);
  }
  async function copy() {
    try {
      await navigator.clipboard.writeText(reportText(a, t));
      setCopied(true);
      setTimeout(() => setCopied(false), 1500);
    } catch { alert("Could not copy."); }
  }
  async function ask() {
    const question = q.trim();
    if (!question) return;
    setQ("");
    const history = chat.filter((m) => !m.err).map(({ role, text }) => ({ role, text }));
    setChat((c) => [...c, { role: "user", text: question }, { role: "model", text: "…" }]);
    try {
      const d = await post("/api/ask", { question, context: a, history, lang });
      setChat((c) => [...c.slice(0, -1), { role: "model", text: d.answer }]);
    } catch (e) {
      setChat((c) => [...c.slice(0, -1), { role: "model", text: e.message, err: true }]);
    }
  }

  return (
    <div className="sheet" ref={ref}>
      <section className="verdict">
        <div className="stamp slam" key={id} style={{ "--c": col }}>
          <b>{s}</b>
          <span>{t["v" + (s >= 67 ? 3 : s >= 34 ? 2 : 1)]}</span>
        </div>
        <div>
          <div className="tag">{a.document_type}</div>
          <h2 id="oneLine">{a.one_line_summary}</h2>
          <div className="chips">
            {["high", "medium", "low"].map((v) => cnt[v] > 0 && <span key={v} className={"badge " + v}>{cnt[v]} {t["s" + v[0]]}</span>)}
          </div>
          <p id="plain">{a.plain_summary}</p>
          <div className="row noprint">
            <button className="ghost small" onClick={listen}>{speaking ? t.stop : t.listen}</button>
            <button className="ghost small" onClick={copy}>{copied ? t.copied : t.copy}</button>
            <button className="ghost small" onClick={() => window.print()}>{t.save}</button>
          </div>
        </div>
      </section>

      <section>
        <h2>{t.facts}</h2>
        <div className="grid">
          {(a.key_facts || []).map((k, i) => <div className="fact" key={i}><b>{k.label}</b><span>{k.value}</span></div>)}
        </div>
      </section>

      <section>
        <h2>{t.risks}</h2>
        {clauses.map((k, i) => <Clause key={id + "-" + i} k={k} doc={a.document_type} lang={lang} t={t} />)}
      </section>

      <section className="cols">
        <div><h2>{t.q}</h2><List items={a.questions_to_ask} /></div>
        <div><h2>{t.m}</h2><List items={a.missing_protections} /></div>
        <div><h2>{t.n}</h2><List items={a.next_steps} /></div>
      </section>

      <section className="noprint">
        <h2>{t.chat}</h2>
        <div className="chat-log" ref={logRef}>
          {chat.map((m, i) => <div key={i} className={"msg " + (m.role === "user" ? "user" : "") + (m.err ? " err" : "")}>{m.text}</div>)}
        </div>
        <div className="row" style={{ marginTop: 0 }}>
          <input type="text" value={q} placeholder={t.ph} onChange={(e) => setQ(e.target.value)} onKeyDown={(e) => e.key === "Enter" && ask()} />
          <button onClick={ask}>{t.ask}</button>
        </div>
      </section>
    </div>
  );
}

/* ---------- comparison result ---------- */
function Comparison({ c, t }) {
  const cls = { better: "low", worse: "high", neutral: "medium" };
  return (
    <div className="panel">
      <h2>{t.hCmp}</h2>
      <div style={{ marginBottom: 8 }}>{c.overall}</div>
      {(c.changes || []).map((x, i) => {
        const eff = cls[x.effect] ? x.effect : "neutral";
        return (
          <div className="chg" key={i}>
            <span className={"badge " + cls[eff]}>{t[eff]}</span><b>{x.topic}</b>
            <div>{t.was}: {x.old_version}</div>
            <div>{t.now}: {x.new_version}</div>
            <div className="tag">{x.explanation}</div>
          </div>
        );
      })}
      {(c.watch_out || []).length > 0 && <><h2 style={{ marginTop: 14 }}>{t.hWatch}</h2><List items={c.watch_out} /></>}
    </div>
  );
}

/* ---------- app ---------- */
export default function App() {
  const [lang, setLang] = useState("en");
  const [text, setText] = useState("");
  const [text2, setText2] = useState("");
  const [image, setImage] = useState(null);
  const [preview, setPreview] = useState("");
  const [analysis, setAnalysis] = useState(null);
  const [runId, setRunId] = useState(0);
  const [cmp, setCmp] = useState(null);
  const [showCmp, setShowCmp] = useState(false);
  const [status, setStatus] = useState({});
  const [busy, setBusy] = useState(false);
  const [drag, setDrag] = useState(false);
  const t = T[lang];

  async function run(l = lang) {
    window.speechSynthesis?.cancel();
    setBusy(true);
    setStatus({ msg: T[l].busy, kind: "busy" });
    try {
      const d = await post("/api/analyze", { text, image, lang: l });
      setAnalysis(d);
      setRunId((n) => n + 1);
      setStatus({});
    } catch (e) {
      setStatus({ msg: e.message, kind: "err" });
    }
    setBusy(false);
  }

  async function compare() {
    setBusy(true);
    setStatus({ msg: t.comparing, kind: "busy" });
    try {
      setCmp(await post("/api/compare", { a: text, b: text2, lang }));
      setStatus({});
    } catch (e) {
      setStatus({ msg: e.message, kind: "err" });
    }
    setBusy(false);
  }

  async function handleFile(f) {
    if (!f) return;
    try {
      if (f.type === "application/pdf") {
        setStatus({ msg: t.pdf, kind: "busy" });
        const data = (await readAsDataURL(f)).split(",")[1];
        const d = await post("/api/pdf", { data });
        setText(d.text); setImage(null); setPreview(""); setStatus({});
      } else {
        const { url, image } = await loadImage(f);
        setImage(image); setPreview(url);
      }
    } catch (e) {
      setStatus({ msg: e.message, kind: "err" });
    }
  }

  function changeLang(l) {
    setLang(l);
    if (analysis && (text.trim() || image)) run(l);
  }

  function clear() {
    window.speechSynthesis?.cancel();
    setText(""); setText2(""); setImage(null); setPreview(""); setAnalysis(null); setCmp(null); setStatus({});
  }

  return (
    <div className="wrap">
      <header className="top">
        <div className="brand">
          <svg width="30" height="30" viewBox="0 0 32 32" fill="none" stroke="currentColor" strokeWidth="2.4" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
            <path d="M8 3h11l6 6v6M8 3v26h8" /><path d="M12 12h8M12 17h4" /><circle cx="22" cy="23" r="5" /><path d="m26 27 4 4" />
          </svg>
          Legal Lens
        </div>
        <div className="seg">
          {[["en", "English"], ["hi", "हिन्दी"]].map(([l, name]) => (
            <button key={l} className={lang === l ? "on" : ""} onClick={() => changeLang(l)}>{name}</button>
          ))}
        </div>
      </header>

      <section className="hero">
        <h1>{t.hero}</h1>
        <div className="tag">{t.tag}</div>
      </section>

      <div
        className={"panel noprint" + (drag ? " drag" : "")}
        onDragOver={(e) => { e.preventDefault(); setDrag(true); }}
        onDragLeave={() => setDrag(false)}
        onDrop={(e) => { e.preventDefault(); setDrag(false); handleFile(e.dataTransfer.files[0]); }}
      >
        <textarea
          aria-label="Document text" value={text} onChange={(e) => setText(e.target.value)}
          placeholder="Paste your contract, rent agreement, loan terms or legal notice here, or drop a PDF or photo on this box."
        />
        <div className="row">
          <label className="btn ghost">Upload PDF / photo
            <input type="file" accept="image/*,application/pdf" hidden onChange={(e) => { handleFile(e.target.files[0]); e.target.value = ""; }} />
          </label>
          {preview && <img id="preview" style={{ display: "block" }} src={preview} alt="preview" />}
          <button className="ghost" onClick={() => setText(SAMPLE)}>Try a sample rent agreement</button>
          <button className="ghost" onClick={clear}>Clear</button>
          <button className="ghost" onClick={() => setShowCmp((v) => !v)}>{t.cmp}</button>
          <button id="go" disabled={busy} onClick={() => run()}>{t.go}</button>
        </div>
        <div id="status" className={"tag " + (status.kind || "")} style={{ marginTop: 12 }}>{status.msg}</div>
        {showCmp && (
          <div style={{ marginTop: 16 }}>
            <div className="tag" style={{ marginBottom: 6 }}>{t.cmpHint}</div>
            <textarea value={text2} onChange={(e) => setText2(e.target.value)} placeholder={t.cmpPh} />
            <div className="row"><button disabled={busy} onClick={compare}>{t.cmpGo}</button></div>
          </div>
        )}
      </div>

      {cmp && <Comparison c={cmp} t={t} />}
      {analysis && <Result key={runId} a={analysis} id={runId} lang={lang} t={t} />}

      <p className="disc">
        Legal Lens gives general information to help you understand documents. It is not legal advice. For important decisions, consult a qualified lawyer. Documents are sent to the Gemini API for analysis and are not stored by this app.
      </p>
    </div>
  );
}
